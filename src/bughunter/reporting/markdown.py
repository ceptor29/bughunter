from __future__ import annotations

from datetime import datetime, timezone
from typing import Any


def generate_markdown_report(ctx: Any, scan_id: str, target: str, elapsed: float) -> str:
    lines = [
        "# BUGHUNTER Scan Report",
        "",
        f"**Target:** `{target}`",
        f"**Scan ID:** `{scan_id}`",
        f"**Date:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        f"**Elapsed:** {elapsed:.1f}s",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "|--------|------:|",
        f"| Subdomains discovered | {len(ctx.subdomains)} |",
        f"| Alive hosts | {len(ctx.alive_hosts)} |",
        f"| Forms found | {len(ctx.forms)} |",
        f"| Parameters found | {len(ctx.params)} |",
        f"| JS files found | {len(ctx.js_files)} |",
        f"| Findings | {len(ctx.findings)} |",
        f"| Errors | {len(ctx.errors)} |",
        "",
    ]

    if ctx.alive_hosts:
        lines.append("## Alive Hosts")
        lines.append("")
        lines.append("| URL | Status | Title | Server | Tech |")
        lines.append("|-----|-------:|-------|--------|------|")
        for h in ctx.alive_hosts:
            tech = ", ".join(h.get("tech", []))[:50]
            title = h.get("title", "")[:40]
            lines.append(f"| {h['url']} | {h['status']} | {title} | {h.get('server', '')} | {tech} |")
        lines.append("")

    if ctx.forms:
        lines.append("## Forms")
        lines.append("")
        for i, f in enumerate(ctx.forms[:20]):
            inputs = ", ".join(inp["name"] for inp in f["inputs"] if inp["name"])
            lines.append(f"- **{f['method']}** `{f['action']}` — inputs: {inputs or '(none)'}")
        lines.append("")

    if ctx.findings:
        lines.append("## Findings")
        lines.append("")
        for finding in ctx.findings:
            lines.append(f"### [{finding.get('severity', 'INFO')}] {finding.get('title', 'Untitled')}")
            lines.append(f"- **Module:** {finding.get('module', 'unknown')}")
            lines.append(f"- **URL:** {finding.get('url', 'N/A')}")
            lines.append(f"- **Evidence:** {finding.get('evidence', 'N/A')[:200]}")
            lines.append("")

    if ctx.errors:
        lines.append("## Errors")
        lines.append("")
        for e in ctx.errors[:10]:
            lines.append(f"- {e}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by BUGHUNTER v0.1.0*")
    return "\n".join(lines)
